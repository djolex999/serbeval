#!/usr/bin/env python
"""Write one `<task>_official` lm-eval YAML per file in data/official/.

Each is the base task's YAML with the same prompt, filters and metrics, pointed at the
official data and tagged `srb_official`, so `--tasks srb_official` runs the whole set.
Re-run after `serbeval official` if the set gains or loses a task.
"""

import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TASKS = ROOT / "lm_eval_tasks"


def main() -> None:
    for stale in TASKS.glob("*_official.yaml"):
        stale.unlink()
    for data in sorted((ROOT / "data" / "official").glob("*.jsonl")):
        task = data.stem
        base = (TASKS / f"{task}.yaml").read_text(encoding="utf-8")
        lines = [line for line in base.splitlines() if not line.startswith(("tag:", "#"))]
        text = "\n".join(lines)
        text = re.sub(r"^task: .*$", f"task: {task}_official\ntag: srb_official", text, count=1,
                      flags=re.M)
        # Replace the whole data_files block (single file or list) with the official file.
        text = re.sub(r"(  data_files:\n    test:)(\n      - .*)+|(  data_files:\n    test:) .*",
                      f"  data_files:\n    test: data/official/{task}.jsonl", text, count=1)
        header = (f"# OFFICIAL SET (generated by scripts/build_official_tasks.py from {task}.yaml).\n"
                  "# Items and their verification status: data/official/MANIFEST.json\n")
        (TASKS / f"{task}_official.yaml").write_text(header + text + "\n", encoding="utf-8")
        print(f"{task}_official")


if __name__ == "__main__":
    main()
